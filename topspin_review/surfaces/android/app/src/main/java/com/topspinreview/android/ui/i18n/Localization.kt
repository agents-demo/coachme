private fun canonical(text: String): String = text
    .replace('–', '-')
    .replace('—', '-')
    .replace('−', '-')
    .replace('\u00A0', ' ')
    .replace('\uFFFD', '-')
    .trim()

private val zhLower = zh.entries.associate { it.key.lowercase() to it.value }
private val zhCanon = zh.entries.associate { canonical(it.key) to it.value }

