object AppLanguage {
    var setting by mutableStateOf("system")
        private set

    var resolved by mutableStateOf(resolveLanguage("system"))
        private set

    fun apply(value: String) {
        setting = value
        resolved = resolveLanguage(value)
    }

    private fun resolveLanguage(value: String): String = when (value) {
        "en", "zh" -> value
        else -> if (Locale.getDefault().language.equals("zh", ignoreCase = true)) "zh" else "en"
    }
}

